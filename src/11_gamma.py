from pathlib import Path

import cv2
import numpy as np


# --------------------------------------------------
# 1. Gamma 결과를 저장할 폴더를 준비한다.
#    사용할 기준 이미지와 dark.jpg 경로도 정한다.
# --------------------------------------------------

reference_path = Path(
    "samples/day02/cap_on_reference.jpg"
)

dark_path = Path(
    "samples/day02/dark.jpg"
)

output_dir = Path(
    "outputs/day02/gamma"
)

output_dir.mkdir(
    parents=True,
    exist_ok=True,
)


# --------------------------------------------------
# 2. dark.jpg를 읽어본다.
# --------------------------------------------------

image = cv2.imread(
    str(dark_path)
)


# --------------------------------------------------
# 3. dark.jpg가 존재하는지 확인한다.
#
#    image가 None이면 이미지를 읽지 못했다는 뜻이다.
# --------------------------------------------------

if image is None:

    # --------------------------------------------------
    # 4. dark.jpg가 없다면
    #    cap_on_reference.jpg를 읽는다.
    # --------------------------------------------------

    print(
        "dark.jpg가 없어 기준 이미지에서 생성합니다."
    )

    reference = cv2.imread(
        str(reference_path)
    )

    if reference is None:
        raise FileNotFoundError(
            f"기준 이미지를 읽지 못했습니다: "
            f"{reference_path}"
        )


    # --------------------------------------------------
    # 5. 기준 이미지의 밝기를 낮춰
    #    dark.jpg를 자동으로 만든다.
    #
    #    alpha=0.55 → 원본 픽셀값을 약 55%로 줄임
    #    beta=0     → 별도의 밝기값을 더하지 않음
    # --------------------------------------------------

    image = cv2.convertScaleAbs(
        reference,
        alpha=0.55,
        beta=0,
    )

    cv2.imwrite(
        str(dark_path),
        image,
    )

    print(
        "문제 이미지 생성:",
        dark_path,
    )


# --------------------------------------------------
# 6. Gamma Correction 함수를 준비한다.
#
#    source → 변환할 이미지
#    gamma  → 적용할 Gamma 값
#
#    함수는 정의한 뒤 10번에서 호출한다.
# --------------------------------------------------

def adjust_gamma(
    source: np.ndarray,
    gamma: float,
) -> np.ndarray:

    # --------------------------------------------------
    # 7. Gamma 값이 0보다 큰지 확인한다.
    #
    #    0 이하이면 오류를 발생시킨다.
    # --------------------------------------------------

    if gamma <= 0:
        raise ValueError(
            "gamma는 0보다 커야 합니다."
        )


    # --------------------------------------------------
    # 8. 0~255의 픽셀값을
    #    Gamma 공식으로 변환하는
    #    Lookup Table을 만든다.
    #
    #    inv_gamma = 1 / gamma
    #
    #    Lookup Table은 원래 픽셀값을
    #    어떤 새로운 값으로 바꿀지 저장한 표이다.
    # --------------------------------------------------

    inv_gamma = 1.0 / gamma

    table = np.array(
        [
            (
                (value / 255.0)
                ** inv_gamma
            ) * 255
            for value in np.arange(256)
        ],
        dtype=np.uint8,
    )

    # Lookup Table을 이미지 전체에 적용한다.
    return cv2.LUT(
        source,
        table,
    )


# --------------------------------------------------
# 9. Gamma 값을 여러 개 준비한다.
#
#    0.6 / 0.8 / 1.0 / 1.2 / 1.5 / 2.0
# --------------------------------------------------

gamma_values = [
    0.6,
    0.8,
    1.0,
    1.2,
    1.5,
    2.0,
]


# --------------------------------------------------
# 10. 첫 번째 Gamma 값을 dark.jpg에 적용한다.
#
#     for 반복문에서 첫 번째 gamma=0.6을 가져온다.
#     adjust_gamma() 함수를 호출한다.
# --------------------------------------------------

for gamma in gamma_values:

    result = adjust_gamma(
        image,
        gamma,
    )


    # --------------------------------------------------
    # 11. 결과 이미지를 저장한다.
    #
    #     적용한 Gamma 값으로 파일명을 만든다.
    # --------------------------------------------------

    output_path = (
        output_dir
        / f"gamma_{gamma}.jpg"
    )

    cv2.imwrite(
        str(output_path),
        result,
    )

    print(
        "저장:",
        output_path,
    )


    # --------------------------------------------------
    # 12. 나머지 Gamma 값도 같은 방법으로 반복한다.
    #
    #     현재 반복이 끝나면 for문이 다음 값을 가져온다.
    #
    #     0.6 → 0.8 → 1.0 → 1.2 → 1.5 → 2.0
    #
    #     각 값마다 10번과 11번을 반복한다.
    # --------------------------------------------------


# --------------------------------------------------
# 13. 모든 결과 이미지를 비교한다.
#
#     아래 폴더에 저장된 6장의 이미지를 직접 확인한다.
#
#     outputs/day02/gamma/
#
#     gamma_0.6.jpg
#     gamma_0.8.jpg
#     gamma_1.0.jpg
#     gamma_1.2.jpg
#     gamma_1.5.jpg
#     gamma_2.0.jpg
# --------------------------------------------------

print("Gamma 비교 이미지 저장 완료")


