from pathlib import Path

import cv2


# --------------------------------------------------
# 1. 1일차에서 만든 병뚜껑 기준 ROI 이미지의 경로를 정한다.
# --------------------------------------------------

reference_path = Path(
    "samples/day02/cap_on_reference.jpg"
)


# --------------------------------------------------
# 2. 실습용으로 만들 어두운 이미지의 저장 경로를 정한다.
# --------------------------------------------------

dark_path = Path(
    "samples/day02/dark.jpg"
)


# --------------------------------------------------
# 3. Brightness 비교 결과를 저장할 폴더를 준비한다.
# --------------------------------------------------

output_dir = Path(
    "outputs/day02/brightness"
)

output_dir.mkdir(
    parents=True,
    exist_ok=True,
)


# --------------------------------------------------
# 4. 기준 ROI 이미지를 읽는다.
# --------------------------------------------------

reference = cv2.imread(
    str(reference_path)
)


# --------------------------------------------------
# 5. 이미지가 정상적으로 읽히지 않았다면 오류를 발생시킨다.
# --------------------------------------------------

if reference is None:
    raise FileNotFoundError(
        f"기준 이미지를 읽지 못했습니다: {reference_path}"
    )


# --------------------------------------------------
# 6. 기준 이미지의 밝기를 약 55% 수준으로 낮춘다.
# --------------------------------------------------

dark = cv2.convertScaleAbs(
    reference,
    alpha=0.55,
    beta=0,
)


# --------------------------------------------------
# 7. 어둡게 만든 이미지를 dark.jpg로 저장한다.
# --------------------------------------------------

cv2.imwrite(
    str(dark_path),
    dark,
)

print("문제 이미지 생성:", dark_path)


# --------------------------------------------------
# 8. Brightness를 비교할 beta 값을 준비한다.
#
# alpha = 1.0 고정
# beta = 0, 20, 50, 80
# --------------------------------------------------

settings = [
    (1.0, 0),
    (1.0, 20),
    (1.0, 50),
    (1.0, 80),
]


# --------------------------------------------------
# 9. dark.jpg에 첫 번째 alpha, beta 값을 적용할 준비를 한다.
#
# for 반복문은 settings의 값을 순서대로 가져온다.
# 첫 번째 실행: alpha=1.0, beta=0
# --------------------------------------------------

for alpha, beta in settings:

    # --------------------------------------------------
    # 10. 현재 alpha, beta 값을 적용하고
    #     변환된 결과 이미지를 저장한다.
    # --------------------------------------------------

    result = cv2.convertScaleAbs(
        dark,
        alpha=alpha,
        beta=beta,
    )

    filename = (
        f"alpha_{alpha}_beta_{beta}.jpg"
    )

    output_path = (
        output_dir / filename
    )

    cv2.imwrite(
        str(output_path),
        result,
    )

    print("저장:", output_path)


    # --------------------------------------------------
    # 11. 나머지 beta 값도 같은 방식으로 반복 적용한다.
    #
    # for 반복문이 다음 설정값으로 돌아간다.
    # beta=20 → beta=50 → beta=80
    # --------------------------------------------------


# --------------------------------------------------
# 12. 모든 결과 이미지를 각각 다른 파일명으로 저장한다.
#
# for 반복문이 종료되면 다음 파일이 생성되어 있다.
#
# alpha_1.0_beta_0.jpg
# alpha_1.0_beta_20.jpg
# alpha_1.0_beta_50.jpg
# alpha_1.0_beta_80.jpg
# --------------------------------------------------

print("Brightness 비교 이미지 저장 완료")


