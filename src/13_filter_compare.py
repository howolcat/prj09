#     - 병뚜껑의 외곽 경계는 유지되는가?
#     - 병뚜껑의 세로 홈은 남아 있는가?
#     - 작은 특징까지 사라지지는 않았는가?
#
#     학생이 결과 이미지를 직접 비교하고 분석한다.
# --------------------------------------------------

print("Filter 비교 이미지 저장 완료")