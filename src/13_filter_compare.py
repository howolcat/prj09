from pathlib import Path

import cv2
import numpy as np


# --------------------------------------------------
# 1. 기준 이미지와 Noise 이미지의 경로를 정한다.
#    Filter 결과를 저장할 경로도 정한다.
# --------------------------------------------------

reference_path = Path(
    "samples/day02/cap_on_reference.jpg"
)

noise_path = Path(
    "samples/day02/noise.jpg"
)

output_dir = Path(
    "outputs/day02/filter"
)


# --------------------------------------------------
# 2. Filter 결과를 저장할 폴더를 생성한다.
# --------------------------------------------------

output_dir.mkdir(
    parents=True,
    exist_ok=True,
)


# --------------------------------------------------
# 3. 1일차에서 만든 병뚜껑 기준 ROI 이미지를 읽는다.
# --------------------------------------------------

reference = cv2.imread(
    str(reference_path)
)


# --------------------------------------------------
# 4. 기준 이미지를 정상적으로 읽었는지 확인한다.
#    읽지 못했다면 오류를 발생시킨다.
# --------------------------------------------------

if reference is None:
    raise FileNotFoundError(
        f"기준 이미지를 읽지 못했습니다: "
        f"{reference_path}"
    )


# --------------------------------------------------
# 5. Noise를 생성하기 위한 난수 Seed를 고정한다.
#
#    42는 난수 생성의 시작 기준값이다.
#    같은 이미지와 설정을 사용하면
#    실행할 때마다 동일한 Noise를 만들 수 있다.
# --------------------------------------------------

rng = np.random.default_rng(42)


# --------------------------------------------------
# 6. 기준 이미지에 추가할 Gaussian Noise를 생성한다.
#
#    loc=0      → Noise의 평균값
#    scale=18   → Noise의 표준편차
#    size       → 기준 이미지와 같은 배열 크기
#
#    각 픽셀에 더할 작은 변화량을 생성한다.
# --------------------------------------------------

gaussian_noise = rng.normal(
    loc=0,
    scale=18,
    size=reference.shape,
)


# --------------------------------------------------
# 7. 기준 이미지에 Gaussian Noise를 더한다.
#
#    float32로 변환하여 Noise를 더한 뒤
#    np.clip()으로 픽셀값을 0~255로 제한한다.
#
#    마지막에 uint8 이미지로 변환한다.
# --------------------------------------------------

noisy = reference.astype(
    np.float32
) + gaussian_noise

noisy = np.clip(
    noisy,
    0,
    255,
).astype(np.uint8)


# --------------------------------------------------
# 8. 점 형태 Noise를 추가할 픽셀 개수를 정한다.
#
#    이미지의 높이와 너비를 구한다.
#    전체 픽셀 수의 1%를 Noise 개수로 사용한다.
# --------------------------------------------------

height, width = noisy.shape[:2]

noise_count = int(
    height * width * 0.01
)


# --------------------------------------------------
# 9. 점 Noise를 추가할 위치를 무작위로 선택한다.
#
#    ys → 세로 좌표
#    xs → 가로 좌표
#
#    half → 검정 점과 흰색 점을 나누기 위한 값
# --------------------------------------------------

ys = rng.integers(
    0,
    height,
    noise_count,
)

xs = rng.integers(
    0,
    width,
    noise_count,
)

half = noise_count // 2


# --------------------------------------------------
# 10. 선택한 위치의 절반을 검정 점으로 만든다.
#
#     픽셀값 0 → 검정색
# --------------------------------------------------

noisy[
    ys[:half],
    xs[:half],
] = 0


# --------------------------------------------------
# 11. 나머지 위치를 흰색 점으로 만든다.
#
#     픽셀값 255 → 흰색
#
#     검정 점과 흰색 점이 추가되면서
#     Salt-and-Pepper Noise를 흉내 낸다.
# --------------------------------------------------

noisy[
    ys[half:],
    xs[half:],
] = 255


# --------------------------------------------------
# 12. Gaussian Noise와 점 Noise가 추가된 이미지를
#     noise.jpg로 저장한다.
# --------------------------------------------------

cv2.imwrite(
    str(noise_path),
    noisy,
)

print(
    "문제 이미지 생성:",
    noise_path,
)


# --------------------------------------------------
# 13. Noise가 추가된 이미지를 Gray로 변환한다.
#
#     이후 Filter 비교는 같은 Gray 이미지를
#     기준으로 진행한다.
# --------------------------------------------------

gray = cv2.cvtColor(
    noisy,
    cv2.COLOR_BGR2GRAY,
)


# --------------------------------------------------
# 14. Filter 비교 결과를 저장할 딕셔너리를 만든다.
#
#     original_gray.jpg에는
#     아직 Filter를 적용하지 않은 Gray 이미지를 넣는다.
#
#     이 이미지는 다른 Filter 결과와 비교할 기준이다.
# --------------------------------------------------

results = {
    "original_gray.jpg": gray,


    # --------------------------------------------------
    # 15. Gaussian Blur를 적용한다.
    #
    #     (3, 3) → 3×3 Kernel
    #     (7, 7) → 7×7 Kernel
    #
    #     주변 픽셀의 가중 평균을 이용하여
    #     이미지의 Noise를 부드럽게 줄인다.
    #
    #     Kernel이 커지면 경계도 더 흐려질 수 있다.
    # --------------------------------------------------

    "gaussian_3.jpg": cv2.GaussianBlur(
        gray,
        (3, 3),
        0,
    ),

    "gaussian_7.jpg": cv2.GaussianBlur(
        gray,
        (7, 7),
        0,
    ),


    # --------------------------------------------------
    # 16. Median Blur를 적용한다.
    #
    #     3 → 3×3 Kernel
    #     7 → 7×7 Kernel
    #
    #     주변 픽셀의 중간값을 이용한다.
    #     검정색·흰색 점 Noise 제거에 유리할 수 있다.
    # --------------------------------------------------

    "median_3.jpg": cv2.medianBlur(
        gray,
        3,
    ),

    "median_7.jpg": cv2.medianBlur(
        gray,
        7,
    ),


    # --------------------------------------------------
    # 17. Bilateral Filter를 적용한다.
    #
    #     9  → 주변 픽셀을 고려할 크기
    #     75 → 색상·밝기 차이에 대한 설정값
    #     75 → 공간적 거리 차이에 대한 설정값
    #
    #     경계를 어느 정도 유지하면서
    #     Noise를 줄이기 위한 Filter이다.
    # --------------------------------------------------

    "bilateral.jpg": cv2.bilateralFilter(
        gray,
        9,
        75,
        75,
    ),
}


# --------------------------------------------------
# 18. Filter 결과를 하나씩 가져와 반복한다.
#
#     results.items()에서
#     filename → 저장할 파일명
#     result   → Filter가 적용된 이미지
#
#     두 값을 하나씩 가져온다.
# --------------------------------------------------

for filename, result in results.items():

    # --------------------------------------------------
    # 19. 현재 Filter 결과 이미지의 저장 경로를 만들고
    #     파일로 저장한다.
    #
    #     저장 후 다음 결과로 반복한다.
    # --------------------------------------------------

    output_path = (
        output_dir / filename
    )

    cv2.imwrite(
        str(output_path),
        result,
    )

    print(
        "저장:",
        output_path,
    )


# --------------------------------------------------
# 20. 모든 Filter 결과를 직접 비교한다.
#
#     original_gray.jpg
#     gaussian_3.jpg
#     gaussian_7.jpg
#     median_3.jpg
#     median_7.jpg
#     bilateral.jpg
#
#     확인할 내용:
#
